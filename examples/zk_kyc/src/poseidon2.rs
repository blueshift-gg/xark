/// Round constants parsed to `Fr` **once**, on first use — rather than re-parsing all
/// ~180 decimal strings on every `perm` call.
static RC_EXT_FR: LazyLock<[[Fr; 3]; 8]> =
    LazyLock::new(|| RC_EXT.map(|row| row.map(|s| Fr::from_str(s).unwrap())));
static RC_INT_FR: LazyLock<[Fr; 56]> = LazyLock::new(|| RC_INT.map(|s| Fr::from_str(s).unwrap()));

/// The S-box, `x^5`.
fn sbox(x: Fr) -> Fr {
    let x2 = x * x;
    x2 * x2 * x
}

/// External linear layer M_E = circ(2,1,1): `out[i] = s[i] + Σs`.
fn ext_layer(s: [Fr; 3]) -> [Fr; 3] {
    let t = s[0] + s[1] + s[2];
    [s[0] + t, s[1] + t, s[2] + t]
}

/// Internal linear layer M_I = J + diag([1,1,2]): `out[i] = Σs + DIAG[i]·s[i]`.
fn int_layer(s: [Fr; 3]) -> [Fr; 3] {
    let t = s[0] + s[1] + s[2];
    [t + s[0], t + s[1], t + s[2].double()]
}

/// The Poseidon2 permutation (initial M_E, 4 full, 56 partial, 4 full rounds).
fn perm(mut s: [Fr; 3]) -> [Fr; 3] {
    s = ext_layer(s);
    for r in 0..4 {
        for i in 0..3 {
            s[i] += RC_EXT_FR[r][i];
            s[i] = sbox(s[i]);
        }
        s = ext_layer(s);
    }
    for &rc in RC_INT_FR.iter() {
        s[0] += rc;
        s[0] = sbox(s[0]);
        s = int_layer(s);
    }
    for r in 4..8 {
        for i in 0..3 {
            s[i] += RC_EXT_FR[r][i];
            s[i] = sbox(s[i]);
        }
        s = ext_layer(s);
    }
    s
}

/// Poseidon2 sponge hash, identical to `xark_poseidon2::hash`: capacity lane
/// seeded with the input length, inputs absorbed two-at-a-time by adding into
/// the rate lanes and permuting, first state element squeezed as the digest.
///
/// Takes an array of anything `Into<Fr>` — plain `Fr`, or the circuit's `Field`
/// (`xark` provides `From<Field> for Fr`, host-only). Returns the digest as a decimal.
pub fn hash<T: Into<Fr>, const N: usize>(inputs: [T; N]) -> String {
    let frs: [Fr; N] = inputs.map(Into::into);
    let mut state = [Fr::from(0u64), Fr::from(0u64), Fr::from(N as u64)];
    let mut i = 0;
    while i < N {
        state[0] += frs[i];
        if i + 1 < N {
            state[1] += frs[i + 1];
        }
        state = perm(state);
        i += 2;
    }
    state[0].into_bigint().to_string()
}

