//! Reference constants for `xark-pedersen`'s fixed-base windows, from `ark-grumpkin`.
//!
//! `cargo run --release --bin pedersen_tables -- rust | rustfmt --edition 2024` prints
//! `gadgets/xark-pedersen/src/tables.rs`, `-- lean` prints
//! `formal/Formal/PedersenData.lean`, and `-- kat` prints the known-answer vectors
//! in `gadgets/xark-pedersen/tests/vec.rs`.
//!
//! Window `w < 43` of generator `G` holds `(k + 2)·8^w·G` for `k < 8` (halo2's
//! fixed-base offsets, so every partial sum is a distinct nonzero multiple), and
//! `CORR = −off·G` with `off = Σ_w 2·8^w` removes the offsets at the end.
//!
//! The Lean file states every table point as a step of an addition chain from `G`
//! (`P_j = P_a + P_b`), plus a chain to `(q − 1)·G = −G` (`q` the group order) and
//! one to `off·G`, which `Formal/GrumpkinOrder.lean` checks in the kernel.

use ark_ec::{AffineRepr, CurveGroup};
use ark_ff::{BigInteger, PrimeField};
use ark_grumpkin::{Affine, Fq as Base, Fr as Scalar, Projective};
use num_bigint::BigUint;

const WINDOWS: usize = 43;

/// The generators `G₀, G₁` (derivation in `gadgets/xark-pedersen/src/lib.rs`'s docs).
const GENERATORS: [[&str; 2]; 2] = [
    [
        "5083206013960444200279950714875343028998509784402499812888938851520740463864",
        "2865765882798453005924934609198434488689574281003992091311004806791329233019",
    ],
    [
        "6702321717701145156728393535503061021609887341049508944231879352606054294317",
        "6805153572597533704290353269906054575543118937636820472181004119224603304535",
    ],
];

fn base(s: &str) -> Base {
    Base::from_le_bytes_mod_order(&s.parse::<BigUint>().unwrap().to_bytes_le())
}

fn dec(x: &Base) -> String {
    x.into_bigint().to_string()
}

fn generator(i: usize) -> Affine {
    let g = Affine::new(base(GENERATORS[i][0]), base(GENERATORS[i][1]));
    assert!(g.is_on_curve() && !g.is_zero());
    g
}

/// An addition chain from `G` (point 0): step `j` is point `j + 1 = P_a + P_b`.
struct Chain {
    points: Vec<Affine>,
    steps: Vec<(usize, usize)>,
}

impl Chain {
    fn new(g: Affine) -> Self {
        Chain {
            points: vec![g],
            steps: Vec::new(),
        }
    }
    fn add(&mut self, a: usize, b: usize) -> usize {
        let p = (self.points[a] + self.points[b]).into_affine();
        assert!(!p.is_zero());
        self.points.push(p);
        self.steps.push((a, b));
        self.points.len() - 1
    }
}

/// The chain for generator `g`: the window tables (`entry(w, k)` is point
/// `1 + 8w + k`), then `off·G`, then `(q − 1)·G`. Returns the chain and the indices
/// of `off·G` and `(q − 1)·G`.
fn chain(g: Affine) -> (Chain, usize, usize) {
    let mut c = Chain::new(g);
    let mut b = 0; // 8^w·G
    for _ in 0..WINDOWS {
        let two = c.add(b, b);
        let mut e = two;
        for _ in 1..8 {
            e = c.add(e, b);
        }
        b = two + 6; // entry k = 6 is 8·8^w·G = 8^(w+1)·G
    }
    let entry = |w: usize, k: usize| 1 + 8 * w + k;
    let mut off = entry(0, 0);
    for w in 1..WINDOWS {
        off = c.add(off, entry(w, 0));
    }
    // (q − 1)·G, most significant bit first, from G.
    let q1 = BigUint::from_bytes_le(&Scalar::MODULUS.to_bytes_le()) - 1u32;
    let mut acc = 0;
    for i in (0..q1.bits() - 1).rev() {
        acc = c.add(acc, acc);
        if q1.bit(i) {
            acc = c.add(acc, 0);
        }
    }
    (c, off, acc)
}

fn rust() {
    println!("//! Generated by `cargo run --release --bin pedersen_tables -- rust | rustfmt");
    println!("//! --edition 2024` in `examples/grumpkin_reference` (ark-grumpkin). Don't edit.");
    println!("//!");
    println!("//! `TABLES[i][w][k] = (k + 2)·8^w·Gᵢ` and `CORR[i] = −(Σ_w 2·8^w)·Gᵢ`.");
    println!();
    println!("use xark::Field;");
    println!();
    println!("pub(crate) static TABLES: [[[[Field; 2]; 8]; {WINDOWS}]; 2] = [");
    for i in 0..2 {
        let (c, _, _) = chain(generator(i));
        println!("    [");
        for w in 0..WINDOWS {
            println!("        [");
            for k in 0..8 {
                let p = c.points[1 + 8 * w + k];
                println!(
                    "            [Field::constant(\"{}\"), Field::constant(\"{}\")],",
                    dec(&p.x),
                    dec(&p.y)
                );
            }
            println!("        ],");
        }
        println!("    ],");
    }
    println!("];");
    println!();
    println!("pub(crate) const CORR: [[Field; 2]; 2] = [");
    for i in 0..2 {
        let (c, off, _) = chain(generator(i));
        let p = -c.points[off];
        println!(
            "    [Field::constant(\"{}\"), Field::constant(\"{}\")],",
            dec(&p.x),
            dec(&p.y)
        );
    }
    println!("];");
}

fn lean() {
    println!("-- Generated by `cargo run --release --bin pedersen_tables -- lean` in");
    println!("-- `examples/grumpkin_reference` (ark-grumpkin). Don't edit.");
    println!("import Mathlib.Data.Nat.Basic");
    println!();
    println!("set_option linter.style.header false");
    println!("set_option linter.style.longLine false");
    println!();
    println!("/-!");
    println!("# `xark-pedersen`'s window tables as addition chains");
    println!();
    println!("For generator `Gᵢ`, `chain i` lists steps `(a, b, x, y)`: point `j + 1` of the");
    println!("chain is `(x, y) = P_a + P_b`, from point 0 = `Gᵢ`. Point `1 + 8w + k` is the");
    println!("window table entry `(k + 2)·8^w·Gᵢ`, point `offIdx` is `(Σ_w 2·8^w)·Gᵢ` and point");
    println!("`qIdx` is `(q − 1)·Gᵢ`. `Formal/GrumpkinOrder.lean` checks every step.");
    println!("-/");
    println!();
    println!("namespace Xark.PedersenData");
    println!();
    for i in 0..2 {
        let g = generator(i);
        let (c, off, q1) = chain(g);
        println!("/-- Generator `G{i}`. -/");
        println!("def gen{i} : ℕ × ℕ := ({}, {})", dec(&g.x), dec(&g.y));
        println!();
        println!("def offIdx{i} : ℕ := {off}");
        println!("def qIdx{i} : ℕ := {q1}");
        println!();
        println!("set_option maxRecDepth 100000 in");
        println!("/-- The addition chain from `G{i}`. -/");
        println!("def chain{i} : List (ℕ × ℕ × ℕ × ℕ) := [");
        let n = c.steps.len();
        for (j, &(a, b)) in c.steps.iter().enumerate() {
            let p = c.points[j + 1];
            let sep = if j + 1 < n { "," } else { "" };
            println!("  ({a}, {b}, {}, {}){sep}", dec(&p.x), dec(&p.y));
        }
        println!("]");
        println!();
    }
    println!("end Xark.PedersenData");
}

fn kat() {
    let one = BigUint::from(1u32);
    let all_sevens: BigUint = (0..42).fold(BigUint::from(0u32), |acc, w| {
        acc | (BigUint::from(7u32) << (3 * w))
    });
    let max: BigUint = (BigUint::from(1u32) << 128u32) - 1u32;
    let cases: Vec<(&str, BigUint, BigUint)> = vec![
        (
            "REFERENCE",
            "1512366075204170929049582354406559215".parse().unwrap(),
            "338770000845734292534325025077361652240".parse().unwrap(),
        ),
        ("ONES", one.clone(), one.clone()),
        ("ALL_SEVENS", all_sevens.clone(), all_sevens),
        ("MAX", max.clone(), max.clone()),
        ("TOP_BIT", BigUint::from(1u32) << 127, one),
    ];
    for (name, m0, m1) in cases {
        let s = |m: &BigUint| Scalar::from_le_bytes_mod_order(&m.to_bytes_le());
        let h: Projective = generator(0).into_group() * s(&m0) + generator(1).into_group() * s(&m1);
        let h = h.into_affine();
        println!(
            "const {name}: [&str; 4] = [\"{m0}\", \"{m1}\", \"{}\", \"{}\"];",
            dec(&h.x),
            dec(&h.y)
        );
    }
}

