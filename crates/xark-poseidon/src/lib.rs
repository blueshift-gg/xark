/// MDS (linear mixing): multiply the state by the fixed MDS matrix. Every entry
/// is a compile-time constant, so each `M[i][j] * state[j]` folds into the linear
/// combination — this layer emits ZERO gates.
fn mds(state: [Field; T]) -> [Field; T] {
    let m = mds_matrix();
    [
        m[0][0] * state[0] + m[0][1] * state[1] + m[0][2] * state[2],
        m[1][0] * state[0] + m[1][1] * state[1] + m[1][2] * state[2],
        m[2][0] * state[0] + m[2][1] * state[1] + m[2][2] * state[2],
    ]
}

/// A full round: ARK, then apply the S-box to ALL `t` state elements, then MDS.
fn full_round(state: [Field; T], rc: [Field; T]) -> [Field; T] {
    let mut s = ark(state, rc);
    let mut i = 0usize;
    while i < 3usize {
        s[i] = sbox(s[i]);
        i += 1;
    }
    mds(s)
}

/// A partial round: ARK, then apply the S-box to `state[0]` ONLY, then MDS.
fn partial_round(state: [Field; T], rc: [Field; T]) -> [Field; T] {
    let mut s = ark(state, rc);
    s[0] = sbox(s[0]);
    mds(s)
}

