//! The base-field certificate of the Ed25519 verifier: `a₁·b₁ − a₂·b₂ − a₃·b₃ ≡ t
//! (mod p)` for `p = 2²⁵⁵ − 19` over 8 × 32-bit limbs that may be unreduced.
//!
//! zkGolf's pseudo-Mersenne folded certificate (secp256k1-scalar-mul record d26e5e80,
//! `MulModFold`), as `xark_bignum::mul_cert_k1` uses it, with two changes forced by `p`:
//! `2²⁵⁶ ≡ 38 (mod p)` and 38 is not a square in BN254's `Fr`, so `X⁸ − 38` has no roots
//! there and the products are taken at the 15 points `0..15` of the degree-14 product
//! (Toom–Cook interpolation, xJsnark's O(m) check) and folded by 38 linearly; and the
//! residual `E = L + 2¹²⁸·U` is a multiple of `p = 2²⁵⁵ − 19`, so the closing row is
//! `L + 19·K = 2¹²⁸·T` with `T = 2¹²⁷·K − U`.

use xark::{Field, require_eq};

/// A base-field element: 8 little-endian 32-bit limbs (value `Σ 2^(32i)·limbᵢ`).
pub type Fe = [Field; 8];

/// Limb bound `mul_cert_25519` assumes of every operand and of `t` (`< 2^CERT_IN`,
/// caller-enforced).
pub(crate) const CERT_IN: u32 = 36;
/// Widths of the range-checked wires `K + 2⁵¹` and `T + 2⁵⁰`.
const CERT_K: usize = 52;
const CERT_T: usize = 51;

/// `2^e` as a field constant.
pub(crate) fn pow2(e: u32) -> Field {
    let mut p = Field::from(1u8);
    let mut i = 0u32;
    while i < e {
        p = p + p;
        i += 1;
    }
    p
}

/// `j^i` for the 15 evaluation points `j` and limb indices `i < 8` (`14⁷ < 2⁶⁴`).
const POW: [[u64; 8]; 15] = {
    let mut t = [[0u64; 8]; 15];
    let mut j = 0;
    while j < 15 {
        let mut v = 1u64;
        let mut i = 0;
        while i < 8 {
            t[j][i] = v;
            v *= j as u64;
            i += 1;
        }
        j += 1;
    }
    t
};

