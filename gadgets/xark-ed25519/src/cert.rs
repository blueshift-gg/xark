/// `V(j) = Σᵢ jⁱ·vᵢ`, the limb polynomial at the point `j`.
fn at(v: Fe, j: usize) -> Field {
    let mut acc = v[0];
    let mut i = 1;
    while i < 8 {
        acc = acc + Field::from(POW[j][i]) * v[i];
        i += 1;
    }
    acc
}

/// Assert `a₁·b₁ − a₂·b₂ − a₃·b₃ ≡ t (mod p)`, `p = 2²⁵⁵ − 19`, for 8 × 32-bit limb
/// vectors whose limbs are in `[0, 2^36)` (the caller enforces it; a constant `0`
/// operand drops its product). The products of the limb polynomials at the points
/// `0..15` (15 rows each) give the folded columns `d_k` of `a₁b₁ − a₂b₂ − a₃b₃` modulo
/// `X⁸ − 38` linearly; with `L = Σ_{k<4} 2^(32k)(d_k − t_k)`, `U = Σ_{k<4} 2^(32k)(d_{k+4} − t_{k+4})`
/// the value `E = L + 2¹²⁸·U` is `≡ a₁b₁ − a₂b₂ − a₃b₃ − t`, and the row
/// `L + 19·K = 2¹²⁸·T` with `K + 2⁵¹ < 2⁵²` and `T + 2⁵⁰ < 2⁵¹` range-checked,
/// `T = 2¹²⁷·K − U`, says `E = K·p` over the integers. Rows: `15` per product,
/// `52 + 51 + 1`. Proven sound over its exported rows
/// (`formal/Formal/MulCert25519.lean`).
#[xark::gadget]
#[allow(clippy::too_many_arguments)]
pub fn mul_cert_25519(a1: Fe, b1: Fe, a2: Fe, b2: Fe, a3: Fe, b3: Fe, t: Fe) {
    // No-wrap budget (bug checklist 5), proven exactly in MulCert25519.lean: a column
    // of the fold has at most 1 + 38·7 = 267 products of three pairs, so
    // |d_k − t_k| < 2^(2·CERT_IN + 10); then |K| ≤ |E|/p < 2^(2·CERT_IN + 10 − 31),
    // |T| = |L + 19K|/2^128 < 2^(2·CERT_IN + 10 − 32), and |L|, 2^128·|T| stay below
    // 2^(2·CERT_IN + 10 + 97), far below r/2.
    const {
        let w = 2 * CERT_IN as usize + 10;
        assert!(w - 31 + 1 == CERT_K && w - 32 + 1 == CERT_T && w + 97 < 252);
    };
    let zero = Field::from(0u8);
    let mut d = [zero; 8];
    let mut j = 0usize;
    while j < 15 {
        let prod = at(a1, j) * at(b1, j) - at(a2, j) * at(b2, j) - at(a3, j) * at(b3, j);
        let mut k = 0usize;
        while k < 8 {
            d[k] = d[k] + CERT_M[k][j] * prod;
            k += 1;
        }
        j += 1;
    }
    let mut lo = zero;
    let mut hi = zero;
    let mut w = Field::from(1u8);
    let mut k = 0usize;
    while k < 4 {
        lo = lo + w * (d[k] - t[k]);
        hi = hi + w * (d[k + 4] - t[k + 4]);
        w = w * pow2(32);
        k += 1;
    }
    // Honestly `E = K·p` with `|L + 19K| < 2^178`, so `K = ⌊(U + 2¹²⁶)/2¹²⁷⌋`; the
    // `+ 2¹⁷⁹ = 2⁵²·2¹²⁷` keeps the operand non-negative. The remainder is scratch:
    // computed in a witness region, read by no row.
    xark::witness_begin();
    let q = Field::hint_div_rem(hi + pow2(126) + pow2(179), pow2(127))[0];
    xark::witness_end();
    let kk = q - pow2(52);
    let tt = kk * pow2(127) - hi;
    let _ = (kk + pow2(51)).to_bits::<CERT_K>();
    let _ = (tt + pow2(50)).to_bits::<CERT_T>();
    require_eq(lo + Field::from(19u8) * kk, pow2(128) * tt);
}
